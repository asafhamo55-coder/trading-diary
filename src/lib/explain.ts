// it is calculated, in Hebrew (default) with an optional English version.
//
// Every explanation mirrors the formula in the code it describes — keep them
// in sync when a calculation changes:
//   savings.ts (net worth, fees, fee drag, liquidity, retirement, coverage),
//   fx.ts / fx-server.ts (exchange rate), guidelines.ts (trade rules),
//   property.ts / property-portfolio.ts / property-attention.ts (rentals),
//   equity-coach.ts + app/page.tsx (cash flow), advisor-report.ts (advisor).
//
// Markup: wrap left-to-right runs (English terms, tickers, numbers with
// symbols) in {curly braces}; <InfoTip> renders them as bidi-isolated <bdi>.
// No personal data here: the repo is public.

