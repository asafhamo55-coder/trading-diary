export type ExplainKey = keyof typeof GLOSSARY;

export const EXPLAIN: Record<ExplainKey, ExplainEntry> = GLOSSARY;

export const EXPLAIN_KEYS = Object.keys(GLOSSARY) as ExplainKey[];

export function isExplainKey(k: string): k is ExplainKey {
  return Object.prototype.hasOwnProperty.call(GLOSSARY, k);
}

/** The text for a key in a language; falls back to Hebrew when `en` is missing. */
export function explainText(key: ExplainKey, lang: "he" | "en" = "he"): { text: ExplainText; lang: "he" | "en" } {
  const e = EXPLAIN[key];
  if (lang === "en" && e.en) return { text: e.en, lang: "en" };
  return { text: e.he, lang: "he" };
}

/** Split `{ltr}` markup into plain and bidi-isolated runs. */
export function splitBidi(s: string): { text: string; ltr: boolean }[] {
  const out: { text: string; ltr: boolean }[] = [];
  const re = /\{([^{}]+)\}/g;
  let last = 0;
  let m: RegExpExecArray | null;
  while ((m = re.exec(s))) {
    if (m.index > last) out.push({ text: s.slice(last, m.index), ltr: false });
    out.push({ text: m[1], ltr: true });
    last = m.index + m[0].length;
  }
  if (last < s.length) out.push({ text: s.slice(last), ltr: false });
  return out;
}
